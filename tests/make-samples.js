/* Builds the bundled sample patterns: node tests/make-samples.js
 * Writes samples/*.gtt and js/samples.js (the same text, embedded so the
 * app also works when index.html is opened straight from disk).
 */
'use strict';
const fs = require('fs');
const path = require('path');
const { DOMParser, XMLSerializer } = require('@xmldom/xmldom');
global.GTT = { _DOMParser: DOMParser, _XMLSerializer: XMLSerializer };
require('../js/colour.js');
require('../js/gttio.js');

const pal = GTT.colour.defaultPalette();
// Natural-dye colours in the first slots
const MADDER = 0, WELD = 1, WOAD = 2, UNDYED = 3, WALNUT = 4;
pal[MADDER] = '#9e3b2e'; pal[WELD] = '#d4a72c'; pal[WOAD] = '#2c5677'; pal[UNDYED] = '#ede6d3'; pal[WALNUT] = '#4a3426';

function chevrons() {
  const n = 24, cards = [];
  for (let i = 0; i < n; i++) {
    const j = i < n / 2 ? i : n - 1 - i;
    let holes;
    if (j < 2) holes = [WALNUT, WALNUT, WALNUT, WALNUT];
    else {
      const base = [MADDER, WELD, WOAD, UNDYED];
      holes = base.map((_, h) => base[(h + j) % 4]);
    }
    cards.push({ number: i + 1, holes, threading: i < n / 2 ? 'S' : 'Z' });
  }
  const picks = [];
  for (let rep = 0; rep < 3; rep++) {
    for (const dir of ['F', 'B']) for (let k = 0; k < 8; k++) {
      picks.push(cards.map((_, c) => ({ type: 'Turn', target: 'Card', id: String(c + 1), dir, dist: 1 })));
    }
  }
  return {
    kind: 'threaded', name: 'Woad and madder chevrons',
    notes: 'A sample pattern for GTT Web.\nTurn all cards 8 forwards, 8 backwards, and repeat.',
    palette: pal, paletteName: 'Natural dyes', cards, packs: [], picks, selvedges: { left: [], right: [] }
  };
}

function packsAndTwists() {
  // 16 cards, two packs turning against each other, with twists at the centre
  const n = 16, cards = [];
  for (let i = 0; i < n; i++) {
    const edge = i < 2 || i >= n - 2;
    cards.push({ number: i + 1, threading: i < n / 2 ? 'S' : 'Z', holes: edge ? [WALNUT, WALNUT, WALNUT, WALNUT] : [WOAD, WOAD, UNDYED, UNDYED] });
  }
  const packs = [
    { name: 'Outer', comment: 'Borders and odd cards', cards: [] },
    { name: 'Inner', comment: 'Even cards', cards: [] }
  ];
  for (let i = 1; i <= n; i++) (i <= 2 || i > n - 2 || i % 2 ? packs[0] : packs[1]).cards.push(i);
  const picks = [];
  const seq = ['F', 'F', 'B', 'B'];
  for (let k = 0; k < 32; k++) {
    const acts = [];
    if (k === 16) [8, 9].forEach(c => acts.push({ type: 'Twist', target: 'Card', id: String(c), dir: 'V', dist: 1 }));
    acts.push({ type: 'Turn', target: 'Pack', id: 'Outer', dir: 'F', dist: 1 });
    acts.push({ type: 'Turn', target: 'Pack', id: 'Inner', dir: seq[k % 4], dist: 1 });
    picks.push(acts);
  }
  return {
    kind: 'threaded', name: 'Packs and twists',
    notes: 'A sample for GTT Web showing pack turning, a twist, and the overlays.',
    palette: pal, paletteName: 'Natural dyes', cards, packs, picks, selvedges: { left: [], right: [] }
  };
}

const out = [
  { file: 'chevrons.gtt', p: chevrons() },
  { file: 'packs-and-twists.gtt', p: packsAndTwists() }
];
const dir = path.join(__dirname, '..', 'samples');
fs.mkdirSync(dir, { recursive: true });
const embedded = [];
for (const { file, p } of out) {
  const text = GTT.io.write(p);
  fs.writeFileSync(path.join(dir, file), text);
  GTT.io.parse(text, file); // sanity check
  embedded.push({ name: p.name, file, text });
}
fs.writeFileSync(path.join(__dirname, '..', 'js', 'samples.js'),
  '/* Generated by tests/make-samples.js. Do not edit by hand. */\n' +
  '(function (GTT) {\n  GTT.samples = ' + JSON.stringify(embedded, null, 1) + ';\n})(window.GTT = window.GTT || {});\n');
console.log('wrote', out.map(o => o.file).join(', '));
